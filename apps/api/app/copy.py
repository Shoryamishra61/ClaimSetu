def meta_payload(*, build_label: str, policy_version: str, poll_interval_seconds: float) -> dict[str, object]:
    """The bundle the SPA fetches once at startup.

    Returned from the API so that a build with a stale frontend bundle still shows
    the current disclosure wording.
    """
    return {
        "simulation": True,
        "build_label": build_label,
        "policy_version": policy_version,
        "poll_interval_seconds": poll_interval_seconds,
        "disclosure": {"en": DISCLOSURE_EN, "hi": DISCLOSURE_HI},
        "about": {"en": ABOUT_EN, "hi": ABOUT_HI},
        "no_real_data": {"en": NO_REAL_DATA_EN, "hi": NO_REAL_DATA_HI},
        "scope": {"en": SCOPE_EN, "hi": SCOPE_HI},
        "confirmation_meaning": {
            "en": CONFIRMATION_MEANING_EN,
            "hi": CONFIRMATION_MEANING_HI,
        },
        "acknowledgement_caveat": {
            "en": ACKNOWLEDGEMENT_CAVEAT_EN,
            "hi": ACKNOWLEDGEMENT_CAVEAT_HI,
        },
        "policy_anchor": {"en": POLICY_ANCHOR_EN, "hi": POLICY_ANCHOR_HI},
    }


