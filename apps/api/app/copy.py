"""Fixed disclosure and honesty copy, in one place.

These strings are requirements, not content. 02_EVIDENCE_AND_CLAIMS_LEDGER.md
fixes what this prototype may claim, and the persistent disclosure is the load-
bearing part of that: a reviewer must be able to tell at a glance that nothing here
touches a government system and no real data is involved.

They live in the API rather than the frontend so there is exactly one authoritative
copy. The SPA fetches them from ``/api/v1/meta`` and renders them verbatim, which
means ``tests/test_copy_lint.py`` can assert the wording once and cover every
screen at the same time.

Rules for editing this file:

*   The three disclosure fragments are verbatim requirements. Rewording them is a
    specification change, not a copy tweak.
*   Nothing here may name a government body as a participant, imply endorsement, or
    describe any output as official, valid, or legally effective.
*   No ``.gov.in`` or ``.nic.in`` string, no logo reference, no seal.
"""

